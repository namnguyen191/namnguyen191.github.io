import {
  CHROMA_SEARCH_MAX,
  contrastRatio,
  deltaEOK,
  type Hex,
  hexToLinearSrgb,
  linearSrgbToOklab,
  maxChroma,
  type OKLab,
  oklabToLinearSrgb,
  oklchToOklab,
  relativeLuminance,
  type RGB,
  srgbToHex,
} from './color-helpers.ts';

export const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950] as const;
export type Step = (typeof STEPS)[number];
export const LIGHTNESS_SCALE = {
  50: 0.98,
  100: 0.95,
  200: 0.9,
  300: 0.84,
  400: 0.74,
  500: 0.64,
  600: 0.54,
  700: 0.47,
  800: 0.39,
  900: 0.3,
  950: 0.21,
} as const satisfies {
  [K in Step]: number;
};

type ChromaRule =
  // share × this hue's own maximum chroma at each step
  | { kind: 'relative'; share: number }
  // share × the lowest maximum among every ramp with kind 'equal', so those ramps match each other
  | { kind: 'equal'; share: number }
  // hand-picked chroma for each step
  | { kind: 'fixed'; values: Record<Step, number> };

type Ramp = {
  role: string; // documentation only; role tokens are mapped in step 10
  hue: number;
  chroma: ChromaRule;
};

// Slate's hand-picked chroma from step 6: lowest at the ends, highest in the middle.
const SLATE_CHROMA = {
  50: 0.004,
  100: 0.008,
  200: 0.013,
  300: 0.018,
  400: 0.025,
  500: 0.03,
  600: 0.032,
  700: 0.032,
  800: 0.03,
  900: 0.028,
  950: 0.026,
} as const satisfies Record<Step, number>;

// Use this value so the weakest status hue isn't right on the gamut edge.
const STATUS_SHARE = 0.9;
export const COLORS = {
  purple: { role: 'brand', hue: 306.9, chroma: { kind: 'relative', share: 0.84 } },
  slate: { role: 'neutral', hue: 257, chroma: { kind: 'fixed', values: SLATE_CHROMA } },
  green: { role: 'success', hue: 158, chroma: { kind: 'equal', share: STATUS_SHARE } },
  red: { role: 'error', hue: 27, chroma: { kind: 'equal', share: STATUS_SHARE } },
  amber: { role: 'warning', hue: 75, chroma: { kind: 'equal', share: STATUS_SHARE } },
  cyan: { role: 'info', hue: 212, chroma: { kind: 'equal', share: STATUS_SHARE } },
} as const satisfies Record<string, Ramp>;
export type RampName = keyof typeof COLORS;

export const STATUS_RAMPS = [
  'red',
  'amber',
  'green',
  'cyan',
] as const satisfies readonly RampName[];
export type StatusRamp = (typeof STATUS_RAMPS)[number];

export const mapSteps = <T>(
  cb: (step: Step) => T
): {
  [K in Step]: T;
} => {
  return Object.fromEntries(STEPS.map((step) => [step, cb(step)])) as {
    [K in Step]: T;
  };
};

const equalChromaColors = Object.values(COLORS).filter(({ chroma }) => chroma.kind === 'equal');
// For each step, the lowest maximum chroma among the 'equal'-rule ramps (the statuses).
// Each of them gets share × this value, so they all have the same chroma at every step.
const equalChromaCeil = mapSteps((step) => {
  const l = LIGHTNESS_SCALE[step];
  // Start above anything maxChroma can return, so the first real value always wins.
  let min = CHROMA_SEARCH_MAX;
  for (const color of equalChromaColors) {
    const h = color.hue;
    const newMax = maxChroma(l, h);
    if (newMax < min) {
      min = newMax;
    }
  }

  return min;
});
export const chromaFor = (rule: ChromaRule, hue: number, step: Step): number => {
  if (rule.kind === 'equal') {
    return equalChromaCeil[step] * rule.share;
  }

  if (rule.kind === 'fixed') {
    return rule.values[step];
  }

  if (rule.kind === 'relative') {
    return maxChroma(LIGHTNESS_SCALE[step], hue) * rule.share;
  }

  const unhandled: never = rule;
  throw new Error(`Unhandled chroma rule: ${JSON.stringify(unhandled)}`);
};

type DtcgColor = {
  colorSpace: 'oklch';
  components: [L: number, C: number, H: number];
  hex: Hex;
};
type SDJsonPalette = {
  [R in RampName]: {
    [S in Step]: {
      $value: DtcgColor;
    };
  };
};

const CHROMA_DECIMALS = 4;
export const generatedPalette = Object.fromEntries(
  Object.entries(COLORS).map(([name, ramp]) => [
    name,
    mapSteps<{
      $value: DtcgColor;
    }>((step) => {
      const oklch = {
        L: LIGHTNESS_SCALE[step],
        C: parseFloat(chromaFor(ramp.chroma, ramp.hue, step).toFixed(CHROMA_DECIMALS)),
        H: ramp.hue,
      };
      const { L, C, H } = oklch;
      return {
        $value: {
          colorSpace: 'oklch',
          components: [L, C, H],
          hex: srgbToHex(oklabToLinearSrgb(oklchToOklab(oklch))),
        },
      };
    }),
  ])
) as SDJsonPalette;

const WHITE: DtcgColor = {
  colorSpace: 'oklch',
  components: [1, 0, 0],
  hex: srgbToHex(oklabToLinearSrgb(oklchToOklab({ L: 1, C: 0, H: 0 }))),
};

export const sdData = {
  palette: {
    $type: 'color',
    $description:
      'Generated by src/scripts/palette_generator/generate_palette_script.ts. Do not edit by hand.',
    ...generatedPalette,
    white: {
      $value: WHITE,
    },
  },
};

export type ColorRef = `${RampName}.${Step}` | 'white';
type Spelling = { linear: RGB; oklab: OKLab };
type Resolved = { oklch: Spelling; hex: Spelling };
export const resolveColor = (colorRef: ColorRef): Resolved => {
  let colorValue: DtcgColor;
  if (colorRef === 'white') {
    colorValue = WHITE;
  } else {
    // ColorRef only allows 'ramp.step', so the split always gives a ramp name and a step.
    const [ramp, step] = colorRef.split('.') as [RampName, `${Step}`];
    colorValue = generatedPalette[ramp][step].$value;
  }
  const {
    components: [L, C, H],
    hex,
  } = colorValue;
  const oklabFromOklch = oklchToOklab({ L, C, H });
  const hexLinear = hexToLinearSrgb(hex);

  return {
    oklch: {
      oklab: oklabFromOklch,
      linear: oklabToLinearSrgb(oklabFromOklch),
    },
    hex: {
      oklab: linearSrgbToOklab(hexLinear),
      linear: hexLinear,
    },
  };
};

export const getMinDeltaEOK = (colorRefA: ColorRef, colorRefB: ColorRef): number => {
  const { hex: hexA, oklch: oklchA } = resolveColor(colorRefA);
  const { hex: hexB, oklch: oklchB } = resolveColor(colorRefB);
  const hexSpellingDelta = deltaEOK(hexA.oklab, hexB.oklab);
  const oklchSpellingDelta = deltaEOK(oklchA.oklab, oklchB.oklab);
  return Math.min(hexSpellingDelta, oklchSpellingDelta);
};

export const getMinContrastRatio = (colorRefA: ColorRef, colorRefB: ColorRef): number => {
  const { hex: hexA, oklch: oklchA } = resolveColor(colorRefA);
  const { hex: hexB, oklch: oklchB } = resolveColor(colorRefB);
  const hexContrastRatio = contrastRatio(
    relativeLuminance(hexA.linear),
    relativeLuminance(hexB.linear)
  );
  const oklchContrastRatio = contrastRatio(
    relativeLuminance(oklchA.linear),
    relativeLuminance(oklchB.linear)
  );

  return Math.min(hexContrastRatio, oklchContrastRatio);
};

export const truncate = (x: number, decimals: number): number =>
  Math.floor(x * 10 ** decimals) / 10 ** decimals;
